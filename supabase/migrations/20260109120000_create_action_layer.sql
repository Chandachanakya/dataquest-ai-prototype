--
-- 1. Create the Action Mapping table.
-- This table is the "brain" of the Action Layer, defining what to do for each state.
--
CREATE TABLE public.action_mapping (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  learner_state TEXT NOT NULL,
  action_type TEXT NOT NULL,
  action_payload JSONB, -- Flexible payload for different actions (e.g., quest ID, UI flag, message)
  priority INT NOT NULL,
  description TEXT, -- Explains the purpose of the action
  
  UNIQUE(learner_state, action_type)
);
COMMENT ON TABLE public.action_mapping IS 'Maps learner states to deterministic, personalized system actions.';

