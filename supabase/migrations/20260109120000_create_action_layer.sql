--
-- 3. Create the Action Logs table for auditability.
-- This is mandatory for academic evaluation and debugging.
--
CREATE TABLE public.action_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  learner_state TEXT NOT NULL,
  action_type TEXT NOT NULL,
  reason TEXT NOT NULL, -- e.g., "State was 'Struggling' due to low scores."
  executed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
COMMENT ON TABLE public.action_logs IS 'Records every personalization action taken by the system for auditability.';

-- Enable RLS for logs
ALTER TABLE public.action_logs ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow service_role to manage logs" ON public.action_logs FOR ALL USING (true);
CREATE POLICY "Users can view their own action logs" ON public.action_logs FOR SELECT USING (auth.uid() = user_id);

--
-- 4. Add a `ui_flags` column to the profiles table.
-- This allows the backend to control UI states (e.g., leaderboard visibility)
-- without changing any frontend code. The frontend would simply read these flags.
--
ALTER TABLE public.profiles
ADD COLUMN IF NOT EXISTS ui_flags JSONB DEFAULT '{}'::jsonb;
COMMENT ON COLUMN public.profiles.ui_flags IS 'Stores UI-related flags set by the personalization engine.';

