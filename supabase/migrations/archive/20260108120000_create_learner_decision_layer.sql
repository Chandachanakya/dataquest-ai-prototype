-- 1. Create the learner_states table to store the computed state for each user.
CREATE TABLE public.learner_states (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  state TEXT NOT NULL,
  reason TEXT NOT NULL,
  computed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  
  UNIQUE(user_id) -- Ensures only one state record per user.
);

-- Enable Row-Level Security
ALTER TABLE public.learner_states ENABLE ROW LEVEL SECURITY;

-- RLS Policies: Allow services to write but let users read their own state.
CREATE POLICY "Allow service_role to manage states" ON public.learner_states
  FOR ALL USING (true);

CREATE POLICY "Users can view their own state" ON public.learner_states
  FOR SELECT USING (auth.uid() = user_id);

-- 2. Create a `learner_analytics` VIEW to aggregate raw data into measurable metrics.
CREATE OR REPLACE VIEW public.learner_analytics AS
SELECT 
  p.id AS user_id,
  
  -- Engagement & Activity Metrics
  MAX(up.completed_at) AS last_active_at,
  COUNT(DISTINCT DATE(up.completed_at)) FILTER (WHERE up.completed_at > NOW() - INTERVAL '30 days') AS activity_frequency, -- Unique active days in last 30 days
  
  -- Performance Metrics
  AVG(up.quiz_score) FILTER (WHERE up.quiz_score IS NOT NULL AND up.completed_at > NOW() - INTERVAL '30 days') AS average_score, -- Avg score in last 30 days (0-100 scale)
  COUNT(up.id) FILTER (WHERE up.completed_at > NOW() - INTERVAL '30 days') AS total_attempts, -- Count of lesson/quiz attempts
  
  -- Progress Metrics
  SUM(q.xp) FILTER (WHERE up.completed = TRUE AND up.completed_at > NOW() - INTERVAL '7 days') AS weekly_xp_earned -- XP earned in the last week

FROM 
  profiles p
LEFT JOIN 
  user_progress up ON p.id = up.user_id
LEFT JOIN
  quests q ON up.quest_id = q.id
GROUP BY 
  p.id;

-- 3. Create the main SQL function to compute and assign learner states.
CREATE OR REPLACE FUNCTION public.evaluate_and_assign_learner_states()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER -- Allows the function to bypass RLS to update the table.
AS $$
DECLARE
  -- These thresholds are configurable and serve as the core of the rule engine.
  DROP_RISK_INACTIVITY_DAYS INT := 14;
  DROP_RISK_LOW_FREQ INT := 2;
  STRUGGLING_AVG_SCORE REAL := 65.0;
  STRUGGLING_MIN_ATTEMPTS INT := 10;
  FAST_AVG_SCORE REAL := 90.0;
  FAST_MIN_XP REAL := 500.0;

BEGIN
  WITH computed_states AS (
    SELECT
      user_id,
      CASE
        -- Priority 1: Drop-risk
        WHEN last_active_at < (NOW() - (DROP_RISK_INACTIVITY_DAYS || ' days')::interval) THEN 
          jsonb_build_object(
            'state', 'Drop-risk',
            'reason', 'User has been inactive for over ' || DROP_RISK_INACTIVITY_DAYS || ' days.'
          )

        WHEN activity_frequency < DROP_RISK_LOW_FREQ THEN 
          jsonb_build_object(
            'state', 'Drop-risk',
            'reason', 'Low engagement: User has been active on fewer than ' || DROP_RISK_LOW_FREQ || ' days in the last month.'
          )

        -- Priority 2: Struggling
        WHEN average_score < STRUGGLING_AVG_SCORE AND total_attempts > STRUGGLING_MIN_ATTEMPTS THEN 
          jsonb_build_object(
            'state', 'Struggling',
            'reason', 'Low performance: Average score is below ' || STRUGGLING_AVG_SCORE || '% despite more than ' || STRUGGLING_MIN_ATTEMPTS || ' recent attempts.'
          )

        -- Priority 3: Fast
        WHEN average_score > FAST_AVG_SCORE AND weekly_xp_earned > FAST_MIN_XP THEN 
          jsonb_build_object(
            'state', 'Fast',
            'reason', 'High performance: Average score is above ' || FAST_AVG_SCORE || '% with rapid XP gain (' || weekly_xp_earned || ' XP this week).'
          )
        
        -- Priority 4: Consistent (Default)
        ELSE 
          jsonb_build_object(
            'state', 'Consistent',
            'reason', 'User is making steady and consistent progress.'
          )
      END AS result
    FROM public.learner_analytics
  )
  -- Perform an "UPSERT"
  INSERT INTO public.learner_states (user_id, state, reason, computed_at)
  SELECT 
    cs.user_id, 
    cs.result->>'state',
    cs.result->>'reason',
    NOW()
  FROM computed_states cs
  ON CONFLICT (user_id) DO UPDATE 
    SET 
      state = EXCLUDED.state,
      reason = EXCLUDED.reason,
      computed_at = NOW();
      
END;
$$;

-- 4. Schedule the function to run daily at midnight UTC.
SELECT cron.schedule('daily-learner-state-evaluation', '0 0 * * *', 'SELECT public.evaluate_and_assign_learner_states();');
