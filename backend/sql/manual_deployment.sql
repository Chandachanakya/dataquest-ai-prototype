-- UTILITY
CREATE OR REPLACE FUNCTION public.update_updated_at() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN NEW.updated_at = NOW(); RETURN NEW; END; $$;

-- PROFILE HANDLER
CREATE OR REPLACE FUNCTION public.handle_new_user() RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER AS $$
BEGIN
  INSERT INTO public.profiles (id, username) VALUES (NEW.id, COALESCE(NEW.raw_user_meta_data->>'username', 'DataQuester'));
  RETURN NEW;
END; $$;

-- ANALYTICS VIEW
CREATE OR REPLACE VIEW public.learner_analytics AS
SELECT 
  p.id AS user_id,
  MAX(up.completed_at) AS last_active_at,
  COUNT(DISTINCT DATE(up.completed_at)) FILTER (WHERE up.completed_at > NOW() - INTERVAL '30 days') AS activity_frequency,
  AVG(up.score) FILTER (WHERE up.score IS NOT NULL AND up.completed_at > NOW() - INTERVAL '30 days') AS average_score,
  COUNT(up.id) FILTER (WHERE up.completed_at > NOW() - INTERVAL '30 days') AS total_attempts,
  SUM(q.xp) FILTER (WHERE up.completed = TRUE AND up.completed_at > NOW() - INTERVAL '7 days') AS weekly_xp_earned
FROM public.profiles p
LEFT JOIN public.user_progress up ON p.id = up.user_id
LEFT JOIN public.quests q ON up.quest_id = q.id
GROUP BY p.id;

-- ACTION EXECUTION
CREATE OR REPLACE FUNCTION public.execute_actions_for_user(target_user_id UUID) RETURNS void LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE
  current_learner_state TEXT;
  state_reason TEXT;
  action_record RECORD;
BEGIN
  SELECT state, reason INTO current_learner_state, state_reason FROM public.learner_states WHERE user_id = target_user_id;
  IF NOT FOUND THEN RETURN; END IF;

  IF EXISTS (SELECT FROM pg_tables WHERE schemaname = 'public' AND tablename = 'action_mapping') THEN
      FOR action_record IN SELECT * FROM public.action_mapping WHERE learner_state = current_learner_state ORDER BY priority ASC LOOP
        INSERT INTO public.action_logs (user_id, learner_state, action_type, reason) VALUES (target_user_id, current_learner_state, action_record.action_type, state_reason);
        CASE action_record.action_type
          WHEN 'ASSIGN_RE_ENGAGEMENT_QUEST' THEN INSERT INTO public.user_progress (user_id, quest_id, completed) VALUES (target_user_id, (action_record.action_payload->>'quest_id'), false) ON CONFLICT (user_id, quest_id) DO NOTHING;
          WHEN 'ASSIGN_REVISION_QUEST' THEN INSERT INTO public.user_progress (user_id, quest_id, completed) VALUES (target_user_id, 'quest-99', false) ON CONFLICT (user_id, quest_id) DO NOTHING;
          WHEN 'ASSIGN_CHALLENGE_QUEST' THEN INSERT INTO public.user_progress (user_id, quest_id, completed) VALUES (target_user_id, (action_record.action_payload->>'quest_id'), false) ON CONFLICT (user_id, quest_id) DO NOTHING;
          WHEN 'CREATE_NOTIFICATION' THEN IF EXISTS (SELECT FROM pg_tables WHERE schemaname = 'public' AND tablename = 'notifications') THEN INSERT INTO public.notifications (user_id, message, read) VALUES (target_user_id, action_record.action_payload->>'message', false) ON CONFLICT (user_id, message) DO NOTHING; END IF;
          WHEN 'SET_UI_FLAG' THEN UPDATE public.profiles SET ui_flags = ui_flags || (action_record.action_payload)::jsonb WHERE id = target_user_id;
          ELSE NULL;
        END CASE;
      END LOOP;
  END IF;
END; $$;

-- STATE EVALUATION
CREATE OR REPLACE FUNCTION public.evaluate_and_assign_learner_states() RETURNS void LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE
  DROP_RISK_INACTIVITY_DAYS INT := 14;
  STRUGGLING_AVG_SCORE REAL := 65.0;
  FAST_AVG_SCORE REAL := 90.0;
BEGIN
  WITH computed_states AS (
    SELECT user_id, CASE
        WHEN last_active_at < (NOW() - (DROP_RISK_INACTIVITY_DAYS || ' days')::interval) THEN jsonb_build_object('state', 'Drop-risk', 'reason', 'Inactive')
        WHEN average_score < STRUGGLING_AVG_SCORE THEN jsonb_build_object('state', 'Struggling', 'reason', 'Low Score')
        WHEN average_score > FAST_AVG_SCORE THEN jsonb_build_object('state', 'Fast', 'reason', 'High Score')
        ELSE jsonb_build_object('state', 'Consistent', 'reason', 'Steady')
      END AS result
    FROM public.learner_analytics
  )
  INSERT INTO public.learner_states (user_id, state, reason, computed_at)
  SELECT cs.user_id, cs.result->>'state', cs.result->>'reason', NOW() FROM computed_states cs
  ON CONFLICT (user_id) DO UPDATE SET state = EXCLUDED.state, reason = EXCLUDED.reason, computed_at = NOW();    
END; $$;

-- TRIGGERS
CREATE OR REPLACE FUNCTION public.trigger_action_execution() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN PERFORM public.execute_actions_for_user(NEW.user_id); RETURN NEW; END; $$;

DO $$ BEGIN
  DROP TRIGGER IF EXISTS on_learner_state_change ON public.learner_states;
  CREATE TRIGGER on_learner_state_change AFTER INSERT OR UPDATE ON public.learner_states FOR EACH ROW EXECUTE FUNCTION public.trigger_action_execution();
EXCEPTION WHEN undefined_table THEN NULL; END $$;


