-- 2. FIX: execute_actions_for_user function (Fixing schema mismatch)
-- Replaces 'status' with 'completed' and removes invalid INT casting for quest_id
CREATE OR REPLACE FUNCTION public.execute_actions_for_user(target_user_id UUID)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  current_learner_state TEXT;
  state_reason TEXT;
  action_record RECORD;
BEGIN
  -- Get the user's current state and the reason it was assigned.
  SELECT state, reason INTO current_learner_state, state_reason
  FROM public.learner_states
  WHERE user_id = target_user_id;

  -- If no state is found, exit.
  IF NOT FOUND THEN
    RETURN;
  END IF;

  -- Loop through all actions defined for the current state, ordered by priority.
  -- Note: ensure action_mapping table exists; failure here means action_mapping usage is skipped
  IF EXISTS (SELECT FROM pg_tables WHERE schemaname = 'public' AND tablename = 'action_mapping') THEN
      FOR action_record IN 
        SELECT * 
        FROM public.action_mapping
        WHERE learner_state = current_learner_state
        ORDER BY priority ASC
      LOOP
        -- Log the action before executing it. 
        INSERT INTO public.action_logs (user_id, learner_state, action_type, reason)
        VALUES (target_user_id, current_learner_state, action_record.action_type, state_reason);

        -- == Execute the action based on its type ==
        CASE action_record.action_type
          WHEN 'ASSIGN_RE_ENGAGEMENT_QUEST' THEN
            -- Fix: Use completed=false instead of status, keep quest_id as TEXT
            INSERT INTO public.user_progress (user_id, quest_id, completed)
            VALUES (target_user_id, (action_record.action_payload->>'quest_id'), false)
            ON CONFLICT (user_id, quest_id) DO NOTHING;

          WHEN 'ASSIGN_REVISION_QUEST' THEN
             -- Fix: Use completed=false instead of status
            INSERT INTO public.user_progress (user_id, quest_id, completed)
            VALUES (target_user_id, 'quest-99', false) -- Assuming generic revision quest is 'quest-99'
            ON CONFLICT (user_id, quest_id) DO NOTHING;

          WHEN 'ASSIGN_CHALLENGE_QUEST' THEN
             -- Fix: Use completed=false instead of status
            INSERT INTO public.user_progress (user_id, quest_id, completed)
            VALUES (target_user_id, (action_record.action_payload->>'quest_id'), false)
            ON CONFLICT (user_id, quest_id) DO NOTHING;

          WHEN 'CREATE_NOTIFICATION' THEN
             -- Ensure notifications table exists before inserting
             IF EXISTS (SELECT FROM pg_tables WHERE schemaname = 'public' AND tablename = 'notifications') THEN
                INSERT INTO public.notifications (user_id, message, read)
                VALUES (target_user_id, action_record.action_payload->>'message', false)
                ON CONFLICT (user_id, message) DO NOTHING;
             END IF;

          WHEN 'SET_UI_FLAG' THEN
            UPDATE public.profiles
            SET ui_flags = ui_flags || (action_record.action_payload)::jsonb
            WHERE id = target_user_id;

          ELSE
            -- Do nothing for unhandled action types.
            NULL;
        END CASE;

      END LOOP;
  END IF;
END;
$$;


-- 3. Create/Update the function to compute states
CREATE OR REPLACE FUNCTION public.evaluate_and_assign_learner_states()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  DROP_RISK_INACTIVITY_DAYS INT := 14;
  DROP_RISK_LOW_FREQ INT := 2;
  STRUGGLING_AVG_SCORE REAL := 65.0;
  STRUGGLING_MIN_ATTEMPTS INT := 10;
  FAST_AVG_SCORE REAL := 90.0;
  FAST_MIN_XP REAL := 500.0;

BEGIN
  -- Re-compute states based on current analytics
  WITH computed_states AS (
    SELECT
      user_id,
      CASE
        -- Priority 1: Drop-risk
        WHEN last_active_at < (NOW() - (DROP_RISK_INACTIVITY_DAYS || ' days')::interval) THEN 
          jsonb_build_object(
            'state', 'Drop-risk',
            'reason', 'User has been inactive for over ' || DROP_RISK_INACTIVITY_DAYS || ' days.'
          )

        WHEN activity_frequency < DROP_RISK_LOW_FREQ THEN 
          jsonb_build_object(
            'state', 'Drop-risk',
            'reason', 'Low engagement: User has been active on fewer than ' || DROP_RISK_LOW_FREQ || ' days in the last month.'
          )

        -- Priority 2: Struggling
        WHEN average_score < STRUGGLING_AVG_SCORE AND total_attempts > STRUGGLING_MIN_ATTEMPTS THEN 
          jsonb_build_object(
            'state', 'Struggling',
            'reason', 'Low performance: Average score is below ' || STRUGGLING_AVG_SCORE || '% despite more than ' || STRUGGLING_MIN_ATTEMPTS || ' recent attempts.'
          )

        -- Priority 3: Fast
        WHEN average_score > FAST_AVG_SCORE AND weekly_xp_earned > FAST_MIN_XP THEN 
          jsonb_build_object(
            'state', 'Fast',
            'reason', 'High performance: Average score is above ' || FAST_AVG_SCORE || '% with rapid XP gain (' || weekly_xp_earned || ' XP this week).'
          )
        
        -- Priority 4: Consistent (Default)
        ELSE 
          jsonb_build_object(
            'state', 'Consistent',
            'reason', 'User is making steady and consistent progress.'
          )
      END AS result
    FROM public.learner_analytics
  )
  -- Perform an "UPSERT"
  INSERT INTO public.learner_states (user_id, state, reason, computed_at)
  SELECT 
    cs.user_id, 
    cs.result->>'state',
    cs.result->>'reason',
    NOW()
  FROM computed_states cs
  ON CONFLICT (user_id) DO UPDATE 
    SET 
      state = EXCLUDED.state,
      reason = EXCLUDED.reason,
      computed_at = NOW();
      
END;
$$;

-- 4. Ensure Trigger Exists (if not already)
CREATE OR REPLACE FUNCTION public.trigger_action_execution()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  PERFORM public.execute_actions_for_user(NEW.user_id);
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_learner_state_change ON public.learner_states;
CREATE TRIGGER on_learner_state_change
  AFTER INSERT OR UPDATE ON public.learner_states
  FOR EACH ROW
  EXECUTE FUNCTION public.trigger_action_execution();

COMMIT;

-- 5. Run the evaluation immediately to populate the table
SELECT public.evaluate_and_assign_learner_states();

